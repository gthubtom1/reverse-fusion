"""Exercise actual original image/3D producers against an owned loopback server.

No paid API call or real credential is used. Generated bytes are transport
fixtures, not a quality claim. Formal candidate outputs remain untouched.
"""
from pathlib import Path
from hashlib import sha256
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import argparse
import base64
import json
import os
import subprocess
import sys
import tempfile
import threading

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from reverse_fusion.mcp_probe import StdioMcp, catalog

parser=argparse.ArgumentParser()
manifest=json.loads((ROOT/'components/craft-mcp/manifest.json').read_text(encoding='utf-8'))
parser.add_argument('--binary',type=Path,default=ROOT/manifest['platforms']['windows-x64']['local_path'])
parser.add_argument('--output',type=Path,required=True)
args=parser.parse_args()
output=args.output.resolve();output.mkdir(parents=True,exist_ok=False)
project=Path(tempfile.mkdtemp(prefix='rf36-craft-asset-outcome-')).resolve()
case=project/'work/current-case';case.mkdir(parents=True)
candidate=project/'candidate/sentinel.txt';candidate.parent.mkdir();candidate.write_bytes(b'formal candidate unchanged')
candidate_before=sha256(candidate.read_bytes()).hexdigest()
fixture_key='rf-local-fixture-key'
environment_key='rf-test-synthetic-environment-key-not-for-network'
png=base64.b64decode('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1kAAAAASUVORK5CYII=')
gltf=json.dumps({'asset':{'version':'2.0'},'scene':0,'scenes':[{}]},separators=(',',':')).encode()
gltf+=b' '*((-len(gltf))%4)
import struct
glb=b'glTF'+struct.pack('<II',2,20+len(gltf))+struct.pack('<I4s',len(gltf),b'JSON')+gltf
requests=[]
class Handler(BaseHTTPRequestHandler):
    def log_message(self,*_):pass
    def do_POST(self):
        body=json.loads(self.rfile.read(int(self.headers['Content-Length'])))
        assert self.headers.get('Authorization')=='Key '+fixture_key
        requests.append({'path':self.path,'body':body,'synthetic_auth_verified':True})
        if body.get('prompt')=='echo-failure':
            code=500;result={'message':'owned provider failure '+fixture_key}
        elif 'image-to-3d' in self.path:
            code=200;result={'model_urls':{'glb':{'url':'data:model/gltf-binary;base64,'+base64.b64encode(glb).decode()}}}
        else:
            code=200;result={'images':[{'url':'data:image/png;base64,'+base64.b64encode(png).decode()}]}
        data=json.dumps(result).encode();self.send_response(code);self.send_header('Content-Length',str(len(data)));self.end_headers();self.wfile.write(data)

server=ThreadingHTTPServer(('127.0.0.1',0),Handler)
worker=threading.Thread(target=server.serve_forever,daemon=True);worker.start()
base=f'http://127.0.0.1:{server.server_port}'
binary=args.binary.resolve()
argv=[str(binary),'--all-tools','--deep-mode','--allow-run','--state-dir',str(output/'server-state')]
environment={k:v for k,v in os.environ.items() if k not in {'REVERSE_FUSION_CRAFT_FAL_KEY','FAL_KEY'}}
calls=[]
def call(client,name,arguments,*,error=False):
    response=client.request('tools/call',{'name':name,'arguments':arguments})
    calls.append({'tool':name,'arguments':arguments,'result':response})
    (output/'calls.json').write_text(json.dumps(calls,ensure_ascii=True,indent=2)+'\n',encoding='ascii')
    assert bool(response.get('isError'))==error,(name,response)
    value=response.get('structuredContent',{})
    return value.get('result',value) if not error else response

request={'kind':'image','prompt':'an owned transport fixture','save_as':'texture.png','budget_usd':1.0,'allow_paid':True}
try:
    for denied in ['https://example.com','http://example.com:80','http://192.0.2.1:8080']:
        invalid=subprocess.run(argv+['--asset-test-base',denied],env=environment,stdin=subprocess.DEVNULL,
                               stdout=subprocess.PIPE,stderr=subprocess.PIPE,timeout=10)
        assert invalid.returncode!=0 and b'loopback' in invalid.stderr
    with StdioMcp(argv,cwd=ROOT,env=environment) as client:
        client.initialize()
        unbound=call(client,'fusion_asset_generate',request,error=True)
        assert 'fusion_case_open' in json.dumps(unbound)
        call(client,'fusion_case_open',{'project_root':str(project),'case_root':str(case)})
        missing=call(client,'fusion_asset_generate',request,error=True)
        assert 'REVERSE_FUSION_CRAFT_FAL_KEY' in json.dumps(missing)
        unprepared=call(client,'assets_image_generate',{'prompt':'fixture','save_as':'x.png'},error=True)
        assert 'project' in json.dumps(unprepared).lower()
    with StdioMcp(argv+['--asset-test-base',base],cwd=ROOT,env={**environment,'REVERSE_FUSION_CRAFT_FAL_KEY':environment_key}) as client:
        client.initialize()
        names={tool['name'] for tool in catalog(client)}
        assert len(names)==305 and 'fusion_asset_generate' in names
        call(client,'fusion_case_open',{'project_root':str(project),'case_root':str(case)})
        refused=call(client,'fusion_asset_generate',{**request,'allow_paid':False},error=True)
        assert 'allow_paid' in json.dumps(refused)
        escaped=call(client,'fusion_asset_generate',{**request,'save_as':'../outside.png'},error=True)
        assert 'relative' in json.dumps(escaped)
        over=call(client,'fusion_asset_generate',{**request,'budget_usd':0.001},error=True)
        assert 'over_limit' in json.dumps(over) and not requests
        image=call(client,'fusion_asset_generate',request)
        assert image['original_tool']=='assets_image_generate' and image['status']=='generated'
        image_dir=Path(image['staging_workspace'].removeprefix('\\\\?\\'))
        assert image_dir.is_relative_to(case/'asset-staging') and (image_dir/'app/texture.png').read_bytes()==png
        model=call(client,'fusion_asset_generate',{'kind':'model3d','prompt':'one original wooden cube','save_as':'models/cube.glb',
                     'budget_usd':1.0,'allow_paid':True,'faces':1000,'textured':True})
        assert model['original_tool']=='assets_model_generate' and len(model['files'])==2
        assert (Path(model['staging_workspace'])/'app/models/cube.glb').read_bytes()==glb
        reference=case/'input.png';reference.write_bytes(png)
        from_image=call(client,'fusion_asset_generate',{'kind':'model3d','image':'input.png','save_as':'cube.glb',
                          'budget_usd':0.5,'allow_paid':True,'faces':500,'textured':False})
        assert from_image['original_result']['result']['cost_usd']==0.4
        failed=call(client,'fusion_asset_generate',{**request,'prompt':'echo-failure'},error=True)
        assert 'engine_missing' in json.dumps(failed)
        assert fixture_key not in json.dumps(failed)
        assert len(requests)==5 and requests[-2]['path'].endswith('image-to-3d')
        assert requests[-2]['body']['image_url'].startswith('data:image/png;base64,')
    assert sha256(candidate.read_bytes()).hexdigest()==candidate_before
    assert not (case/'outside.png').exists()
    for file in [p for base_dir in (case,output) for p in base_dir.rglob('*') if p.is_file()]:
        assert environment_key.encode() not in file.read_bytes(),file
        if file.suffix in {'.json','.jsonl','.log','.toml'}:
            assert fixture_key.encode() not in file.read_bytes(),file
    report={'status':'pass','scope':'actual original image/3D tool and Fal producer over explicit loopback HTTP; no paid service or quality claim',
            'tools':305,'binary_sha256':sha256(binary.read_bytes()).hexdigest(),'case_root':str(case),
            'missing_key_refused':True,'unprepared_original_route_refused':True,'host_allow_required':True,
            'budget_refused_before_network':True,'path_escape_refused':True,'png_generated':True,'glb_generated':True,
            'local_reference_generated':True,'original_provider_error_preserved':True,'credential_redacted':True,
            'formal_candidate_unchanged':True,'nonloopback_fixture_rejected':True,'network_requests':len(requests),'cleanup':client.cleanup}
    (output/'report.json').write_text(json.dumps(report,indent=2)+'\n',encoding='ascii')
    (output/'requests.json').write_text(json.dumps(requests,indent=2)+'\n',encoding='ascii')
    print(json.dumps(report))
finally:
    server.shutdown();server.server_close()
